; A = screen row. Carry if it is in the current screen's scrolling band.
; Preserves everything else.
in_band:
        push bc
        ld c, a
        ld a, (scn_pbank)
        or a
        jr z, .no
        ld a, (scn_row0)
        ld b, a
        ld a, c
        sub b
        jr c, .no
        ld b, a
        ld a, (scn_rows)
        dec a
        cp b                    ; (row - row0) <= rows - 1 ?
        ccf
        jr nc, .no              ; (carry now = row - row0 > rows - 1)
        ld a, c
        scf
        pop bc
        ret
.no:    ld a, c
        or a
        pop bc
        ret

