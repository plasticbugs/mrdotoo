; =============================================================================
; render.asm - playfield renderer (runs inside the vblank NMI)
; =============================================================================
; The arcade keeps its two tile layers in video RAM ($7000-$7FFF here). Every
; arcade store into it goes through vstore (the patched write sites), which
; queues the cell. Each vblank the renderer turns queued cells into Screen 2
; name-table entries:
;
;   code = (bg tile == colourway dirt tile ? TBLA : TBLB)[fg tile]
;
; with the colourway's tables and tile set generated by tools/gen_tiles.py.
;
; Screen mapping (player view, the arcade monitor is rotated):
;   screen column sx = arcade native row - 4          (0-23: the playfield)
;   screen row    sy = (31 - arcade native column) - cam
; cam is the first player-view tile row shown: 3, 4 or 5. The playfield is
; 26 rows (player-view rows 3-28) and the screen shows 24; the camera moves in
; 8px steps to follow Mr. Do.
; =============================================================================

SET_BANK0       equ 4           ; tile sets: 4 per bank, banks 4-11
SETS_PER_BANK   equ 4
SET_MAX         equ 224
SET_BYTES       equ 2 + SET_MAX*16
TBL_BANK        equ 12          ; per colourway: TBLA page, TBLB page; then dirt pairs
SCR_BANK0       equ 15          ; non-gameplay screens: sets, hashes, scene data (tools/gen_screens.py)
SCR_INDEX       equ 16          ; bytes per scr_index entry
SCR_EXTRA       equ 6           ; tools/gen_screens.py SCREENS order
SCR_CONGRATS    equ 7
WONDER_SIG      equ $2D7        ; tools/data/screens/wonderful.txt "sig 2d7 2d"
WONDER_TILE     equ $2D
N_SCREENS       equ (scr_index_end - scr_index) / SCR_INDEX
MODE_NONE       equ 0
MODE_PLAYFIELD  equ 1
MODE_SCREEN     equ 2
DIRT_PAIRS      equ $C000 + 31*512
QUEUE_CELLS     equ 128         ; dirty queue: 128 x 2 bytes, one 256-byte page
DRAIN_MAX       equ 40          ; queued cells drawn per vblank
REDRAW_ROWS     equ 6           ; rows per vblank during a full redraw
REDRAW_ROWS_SCR equ 2           ;   (screen mode: hashed lookups)
PF_ROWS         equ 24
BUSY_MIN        equ 16          ; cell writes per vblank that mean a repaint is still going
RD_WAIT_MAX     equ 30          ; vblanks a full redraw may wait for it
FLIP_WAIT_MAX   equ 8           ; vblanks a finished redraw may wait for the queue
UP_HOLD_MAX     equ 60          ; vblanks a tile-set change may wait for Mr. Do to hide
CAM_TOP         equ 3
CAM_MID         equ 4
CAM_BOTTOM      equ 5
PLAYER_X        equ ARC_WORK + $1C8     ; arcade $E1C8: Mr. Do, movement axis
PLAYER_FLAGS    equ ARC_WORK + $1C5     ; arcade $E1C5: bit 7 = active

; -----------------------------------------------------------------------------
; vstore: the arcade's video store. A = value, HL = address (CV addresses).
; Preserves BC, DE, HL; clobbers AF. Stores into:
;   $7000-$7FFF  video RAM: store + queue the cell
;   $6000-$6FFF  work RAM: plain store
;   $F000-$FFFF  the arcade's scroll registers: latch into the I/O cells
;   elsewhere    ROM on the arcade board: dropped
; -----------------------------------------------------------------------------
vstore:
        ld (vtmp), a
        ld a, h
        cp $80
        jr nc, .hi
        cp $70
        jr c, .lo
        ld a, (vtmp)
        ld (hl), a
        jp queue_cell
.lo:    cp $60
        ret c
        ld a, (vtmp)
        ld (hl), a
        ret
.hi:    cp $F0
        ret c
        cp $F8
        ld a, (vtmp)
        jr nc, .sy
        ld (IO_SCROLL_X), a
        ret
.sy:    ld (IO_SCROLL_Y), a
        ret

; HL = video address -> dirty queue (producer side). Clobbers AF.
; The NMI only advances q_tail and the arcade only advances q_head, so the
; ring needs no locking. A full queue asks for a full redraw instead; while
; one is pending, cells are only counted (the redraw covers them), so a bulk
; repaint (the chomper session's 1248-byte fill) costs little and the
; renderer can tell when it has finished.
queue_cell:
        ld a, (mode)            ; a cutscene band's cell: noted for the next
        cp MODE_SCREEN          ; build (scene_write), never queued, so none
        jr nz, .plain           ; is lost or late
        ld a, (scn_pbank)
        or a
        jr z, .plain
        call scene_write
        ret c
.plain: ld a, (redraw_all)
        or a
        jr nz, .count
        push de
        push hl
        ld a, h
        and 3
        ld d, a
        ld e, l                 ; DE = cell 0-$3FF
        ld a, (q_head)
        ld l, a
        add a, 2
        ld h, a
        ld a, (q_tail)
        cp h
        jr z, .full
        ld a, h
        ld h, high dirty_q
        ld (hl), e
        inc l
        ld (hl), d
        ld (q_head), a          ; publish after the entry is written
        pop hl
        pop de
        ret
.full:  ld a, 1
        ld (redraw_all), a
        pop hl
        pop de
        ret
.count: ld a, (q_busy)
        inc a
        ret z                   ; (saturates at 255)
        ld (q_busy), a
        ret

; The arcade's store forms, reached by rst. All preserve every register and flag.
vh_hl_a:                        ; rst $20: ld (hl),a
        push af
        call vstore
        pop af
        ret
vh_de_a:                        ; rst $28: ld (de),a
        push af
        ex de, hl
        call vstore
        ex de, hl
        pop af
        ret
vh_hl_c:                        ; rst $38: ld (hl),c
        push af
        ld a, c
        call vstore
        pop af
        ret
vh_hl_b:                        ; rst $00: ld (hl),b
        push af
        ld a, b
        call vstore
        pop af
        ret
vh_hl_n:                        ; rst $30 + inline byte: ld (hl),n
        push af
        push hl
        ld hl, 4
        add hl, sp              ; HL -> the return address (points at n)
        push de
        ld e, (hl)
        inc hl
        ld d, (hl)
        ld a, (de)              ; A = n
        inc de
        ld (hl), d              ; return past n
        dec hl
        ld (hl), e
        pop de
        pop hl
        call vstore
        pop af
        ret

; -----------------------------------------------------------------------------
; render: called from the NMI, VDP access allowed. Leaves bank ARC_HI_BANK
; mapped, as the arcade expects.
; -----------------------------------------------------------------------------
render_init:
        xor a
        ld (vgl_on), a
        ld (ico_on), a          ; (vgland.asm: WONDERFUL's icons)
        ld (live_state), a      ; (live.asm: no switch armed)
        ld (scr_xoff), a        ; (no centred screen)
        ld (nmi_late), a
        ld (img_d), a
        ld (up_black), a
        ld (blank_req), a
        ld (scr_hold), a
        ld (logo_on), a
        ld (q_head), a
        ld (q_tail), a
        ld (redraw_all), a
        ld (up_pending), a
        ld a, high VR_PNT
        ld (pnt_front), a
        ld a, high VR_PNT2
        ld (pnt_back), a
        ld a, $FF
        ld (cw), a
        ld (scr), a
        ld (plate_want), a
        ld (plate_food), a
        ld (hud_next), a
        ld (score_want), a
        ld (score_have), a
        xor a
        ld (mode), a
        ld (cw_valid), a
        ld (cw_attr), a
        ld (cw_tile), a
        ld a, PF_ROWS
        ld (rd_row), a
        ld a, CAM_MID
        ld (cam), a
        ret

; Every path out of here must leave ARC_HI_BANK mapped: the arcade's sound data
; and scene code live in that window. render_body may leave any bank mapped.
render:
        call render_body
        ld a, ARC_HI_BANK
        jp select_bank

render_body:
        ld a, (blank_req)       ; the arcade is wiping the screen it showed
        or a
        call nz, go_black
        call scene_vblank       ; a cutscene band's new tiles and names
        call late_ack           ; (safe points: see nmi)
        call extra_check        ; the EXTRA scene starting: its picture
        ld a, (mode)
        cp MODE_IMAGE
        jp z, .image
        or a
        jr z, .nospr
        ld a, (vgl_on)          ; (the VERY GOOD picture has its own sprites)
        or a
        jr nz, .nospr
        ld a, (ico_on)          ; (WONDERFUL: only its icon, vgland.asm)
        or a
        jr z, .noico
        call ico_tick
        jr .nospr
.noico:
        ld a, (logo_on)         ; (so has the romhack clown: its sprites and
        cp 2                    ; the coin here too, logo.asm clown_spr)
        jr z, .clw
        call sprites_update     ; first, inside vblank
        jr .nospr
.clw:   call clown_spr
.nospr:
        call late_ack
        call check_colourway
        ld a, (mode)
        or a
        ret z                   ; no tile set yet
        cp MODE_IMAGE
        ret z                   ; (an image just went up: nothing to draw)
        cp MODE_SCREEN
        jr z, .scrm
        ld a, (plate_want)      ; a new dessert on the playfield: its tiles
        ld hl, plate_food
        cp (hl)
        call nz, plate_load
        ld a, (score_want)      ; a dessert's score: its tile
        ld hl, score_have
        cp (hl)
        call nz, score_load
        call hud_scan           ; the next EXTRA letter's marker (hud.asm)
        ld a, TBL_BANK
        jr .bank
.scrm:
        call scene_update       ; (a cutscene's scrolling band, if any)
        call logo_tick          ; (the romhack logo's colour bars, if any)
        ld a, (scr_hbank)
.bank:  call select_bank
        call apple_sync         ; resting apples as tiles (apples.asm)
        call live_tick          ; a tile set switch's remaining codes (live.asm)
        call camera_update
        ld a, (redraw_all)
        or a
        jr z, .noreq
        ld a, (q_busy)          ; the arcade still writing many cells (a bulk
        cp BUSY_MIN             ; repaint)? Wait for it to finish, keeping
        jr c, .start            ; the old picture on screen
        xor a
        ld (q_busy), a
        ld a, (rd_wait)
        inc a
        ld (rd_wait), a
        cp RD_WAIT_MAX
        jp c, .done
.start: call live_finish        ; (a tile set switch's rest first: the redraw
        xor a                   ; may use any code)
        ld (q_busy), a
        ld (rd_wait), a
        ld (redraw_all), a
        ld (flip_wait), a
        ld (rd_row), a          ; restart the full redraw
        ld a, (q_head)          ; everything queued so far is covered by it
        ld (q_tail), a
.noreq: ld a, (rd_row)
        cp PF_ROWS
        jr nc, .drain
        call redraw_rows        ; into the hidden name table
        ld a, (rd_row)
        cp PF_ROWS
        jr c, .done
        ld a, (q_head)          ; complete. Cells the arcade changed while
        ld (flip_mark), a       ; it ran (it may have been mid-repaint) go
        ld a, FLIP_WAIT_MAX     ; into it too before it is shown: the queue
        ld (flip_wait), a       ; up to here.
        jr .done
.image: call check_colourway   ; (a new screen or playfield ends it)
        ld a, (mode)
        cp MODE_IMAGE
        jp z, image_tick
        ret
.drain: call drain_queue
        ld a, (flip_wait)
        or a
        jr z, .done
        dec a
        ld (flip_wait), a
        jr z, .show             ; (safety: never wait longer than this)
        ld a, (q_tail)
        ld b, a
        ld a, (flip_mark)
        cp b
        jr nz, .done            ; still catching up
        xor a
        ld (flip_wait), a
.show:  ld a, (up_pending)      ; show it, with its new tile set
        or a
        jr nz, .upload
        call flip_pnt
        ld a, (mode)            ; HUD cells written during a bulk repaint were
        cp MODE_PLAYFIELD       ; only counted, not queued
        call z, hud_redraw
        jr .done
.upload:
        call live_try           ; between two playfield sets: switched at the
        jr c, .done             ; next vblank with the display on (live.asm)
        ld a, (ARC_WORK)        ; the dessert sequence ($E000 bit 3; the field
        bit 3, a                ; turns to the chomper colours while Mr. Do is
        jr z, .up               ; still shown): the upload's blank frame would
        ld a, (up_hold)         ; blink him, so it waits until the arcade
        inc a                   ; hides him (~16 vblanks), at most UP_HOLD_MAX
        cp UP_HOLD_MAX
        jr nc, .up
        ld (up_hold), a
        call mrdo_queued
        jr nc, .up
        ld a, 1                 ; try again next vblank
        ld (flip_wait), a
        jr .done
.up:    xor a
        ld (up_hold), a
        call upload_set
.done:  ld a, ARC_HI_BANK
        jp select_bank

; Display off with a black backdrop, no sprites: upload_set turns it back on.
; Clobbers AF, C, HL.
screen_black:
        ld a, VDP_R1_ON & ~$40
        ld c, 1
        call vdp_reg
        ld a, VDP_R7
        ld c, 7
        call vdp_reg
        ld a, 1                 ; (and the upload's blank frame stays black)
        ld (up_black), a
        ld hl, VR_SAT
        call vdp_set_write
        ld a, SAT_END
        out (VDP_DATA), a
        ret

; The arcade is wiping the whole screen of a cutscene or other screen (a
; full-screen fill, opt.asm fill_fast): nothing of it is worth drawing any
; more. Black display, no mode (no cells drawn, no band, no sprites) until
; the next tile set goes up, which turns the display back on. Without this
; the NMI kept rendering the dying screen cell by cell (and the band kept
; tracking it) while the arcade drew the next level: ~3 s after VERY GOOD.
go_black:
        xor a
        ld (blank_req), a
        ld (live_state), a
        call leave_image        ; (an image or the VERY GOOD characters)
        call vgl_leave
        ld a, VDP_R1_ON & ~$40
        ld c, 1
        call vdp_reg
        ld a, VDP_R7
        ld c, 7
        call vdp_reg
        xor a
        ld (mode), a
        ld (redraw_all), a
        ld (flip_wait), a
        ld (cw_valid), a
        ld a, PF_ROWS
        ld (rd_row), a
        ld a, $FF
        ld (cw_attr), a         ; whatever comes next is new
        ld (cw_tile), a
        ld (scr), a
        ld a, 16
        ld (scr_hold), a
        ld a, (q_head)          ; the queue is for the wiped screen
        ld (q_tail), a
        ret

; Carry if the arcade's sprite queue holds a Mr. Do code ($00-$26).
; Clobbers AF, BC, HL.
mrdo_queued:
        ld hl, ARC_WORK + $312
        ld b, 40
.l:     ld a, (hl)
        inc hl
        ld c, (hl)              ; Y = 0 ends the queue
        inc c
        dec c
        jr z, .none
        and $7F
        cp $27
        ret c
        inc hl
        inc hl
        inc hl
        djnz .l
.none:  or a
        ret

; Show the name table the last full redraw went into (a scene's band names
; go into it at the next vblank).
flip_pnt:
        ld a, (scn_pbank)
        or a
        jr z, .noband
        ld a, (mode)
        cp MODE_SCREEN
        jr nz, .noband
        ld (scn_ready), a       ; (nonzero)
.noband:
        ld a, (pnt_back)
        ld b, a
        ld a, (pnt_front)
        ld (pnt_back), a
        ld a, b
        ld (pnt_front), a
        rrca                    ; R2 = PNT / $400
        rrca
        and $3F
        ld c, 2
        jp vdp_reg

; Which colourway is on screen? The arcade fills the playfield background with
; the level's dirt; its bottom-left corner cell ($83) identifies it.
check_colourway:
        ld a, (ARC_FG_TILE + WONDER_SIG)  ; WONDERFUL (after scene 10) keeps
        cp WONDER_TILE          ; the last maze's dirt in cell $083: without
        jr nz, .maze            ; this it stayed a playfield (apples and
        xor a                   ; junk). Its signature wins; the colourway
        ld (cw_valid), a        ; is forgotten so the next maze is found
        dec a
        ld (cw_attr), a
        ld (cw_tile), a         ; (and check_screens's repaint guard passes)
        ld a, ARC_HI_BANK
        call select_bank
        jp check_screens
.maze:  ld a, (ARC_VRAM + $083)
        ld b, a
        ld a, (ARC_VRAM + $483)
        ld c, a
        ld a, (cw_attr)
        cp b
        jr nz, .changed
        ld a, (cw_tile)
        cp c
        jp z, check_screens
.changed:
        ld a, b
        ld (cw_attr), a
        ld a, c
        ld (cw_tile), a
        ld a, TBL_BANK
        call select_bank
        ld hl, DIRT_PAIRS
        ld d, 0
.search:
        ld a, (hl)
        cp b
        jr nz, .next
        inc hl
        ld a, (hl)
        dec hl
        cp c
        jr z, .found
.next:  inc hl
        inc hl
        inc d
        ld a, d
        cp 31
        jr nz, .search
        xor a                   ; not a playfield colourway
        ld (cw_valid), a
        ld a, ARC_HI_BANK
        call select_bank
        jp check_screens
.found: ld a, 1
        ld (cw_valid), a
        ld a, b                 ; (the pair's attribute too: check_screens)
        ld (cw_vattr), a
        ld a, c
        ld (dirt_tile), a
        ld a, d
        ld (tbl_page), a        ; tables at $C000 + cw*512: page = $C0 + cw*2
        add a, a
        add a, $C0
        ld (tbl_page), a
        ld a, (mode)
        cp MODE_PLAYFIELD
        jr nz, .new
        ld a, (cw)
        cp d
        jr z, .out              ; same tile set (colourways can share a pair)
.new:   call leave_image
        xor a                   ; (playfields are never centred: the sprite
        ld (scr_xoff), a        ; pass reads it in every mode)
        ld a, (mode)            ; coming from a screen or an image: the
        sub MODE_PLAYFIELD      ; upload's blank frame stays black (between
        ld (up_black), a        ; two playfields it takes the new dirt colour)
        ld a, d
        ld (cw), a
        ld a, MODE_PLAYFIELD
        ld (mode), a
        call apple_reset
        ld a, d                 ; set cw: bank SET_BANK0 + cw/4, slot cw%4
        srl a
        srl a
        add a, SET_BANK0
        ld b, a
        ld a, d
        call set_address
        ld a, b
        call upload_start
.out:   ld a, ARC_HI_BANK
        jp select_bank

; A = slot (0-3) in a set bank -> HL = its address. Preserves B.
set_address:
        and SETS_PER_BANK-1
        ld hl, $C000
        ld de, SET_BYTES
        or a
        ret z
.mul:   add hl, de
        dec a
        jr nz, .mul
        ret

; Not a playfield: is it one of the captured screens (tools/gen_screens.py)?
; Each has a signature: a cell whose fg tile it always shows.
check_screens:
        ld a, (cw_valid)
        or a
        ret nz
        ld a, (mode)            ; the playfield mid-repaint (a chomper session
        cp MODE_PLAYFIELD       ; starting or ending: the arcade rewrites the
        jr nz, .scr             ; attributes, then the tiles): the pair still
        ld a, (cw_tile)         ; shares its tile or its attribute with the
        ld hl, dirt_tile        ; colourway on screen. Not a screen: maze
        cp (hl)                 ; cells can hold a screen's signature tile
        ret z                   ; (the instruction screen's $8B at $2A7 is a
        ld a, (cw_attr)         ; tunnel piece: it blacked the field)
        ld hl, cw_vattr
        cp (hl)
        ret z
.scr:
        ld a, (scr_hold)        ; just wiped: its signature cell may still be
        or a                    ; there for a moment
        jr z, .look
        dec a
        ld (scr_hold), a
        ret
.look:
        ld hl, scr_index
        ld c, 0
.next:  ld a, c
        cp N_SCREENS
        ret z
        ld e, (hl)
        inc hl
        ld d, (hl)
        inc hl
        push hl
        ld hl, ARC_FG_TILE
        add hl, de
        ld a, (hl)
        pop hl
        cp (hl)
        jr z, .hit
        ld de, SCR_INDEX - 2
        add hl, de
        inc c
        jr .next
.hit:   ld a, (mode)
        cp MODE_SCREEN
        jr z, .same
        cp MODE_IMAGE
        jr nz, .new
        ld a, c                 ; the EXTRA picture stays up until the
        cp SCR_EXTRA            ; playfield returns: its scene's captured
        ret z                   ; screens (still matching while the arcade
        cp SCR_CONGRATS         ; clears them) are not used
        ret z
.same:  ld a, (scr)
        cp c
        ret z
.new:   call leave_image
        ld a, $FF               ; forget the last lookup (new hash table)
        ld (scr_last), a
        ld (scr_last+1), a
        ld a, c
        ld (scr), a
        inc hl                  ; entry +3: camera (fixed per screen)
        ld a, (hl)
        ld (cam), a
        inc hl
        ld a, (hl)              ; set bank
        inc hl
        ld e, (hl)
        inc hl
        ld d, (hl)              ; set address
        inc hl
        push af
        push de
        ld de, scr_hbank        ; hash bank, hash page, band row, band rows,
        ld bc, 6                ; pair hash bank, slot base
        ldir
        xor a
        ld (scn_ready), a       ; a new band starts from scratch
        ld (scn_brow), a
        ld (scn_flush2), a
        ld (scn_lastn), a
        ld (scn_fill), a        ; fill its caches first
        ld (scn_n), a           ; no tiles and a black band until its first
        push hl                 ; build: the full redraw's flip flushes the
        ld hl, SCN_BUF          ; band names, and the last band's (a second
        ld de, SCN_BUF + 1      ; VERY GOOD) pointed at slots that now hold
        ld bc, SCN_BUF_MAX - 1  ; the new set's font: letters in the band
        ld (hl), a
        ldir
        call vgl_check          ; VERY GOOD: its sprites from the first
        call ico_check          ; vblank (else one pass drew the arcade's
        pop hl                  ; round-end icon sprite); WONDERFUL's icon
        inc hl                  ; entry +15: x offset (centred screens)
        inc hl
        ld a, (hl)
        ld (scr_xoff), a
        dec hl                  ; entry +14: the romhack logo (logo.asm)
        ld a, (hl)
        dec hl
        call logo_start
        ld a, (hl)              ; entry +13: image bank (0 = none)
        or a
        jr nz, .image
        ld a, (mode)            ; from the playfield (a round's end into
        cp MODE_PLAYFIELD       ; VERY GOOD / WONDERFUL / ...): black until
        call z, screen_black    ; the new set is up (the arcade's own cells,
        ld a, MODE_SCREEN       ; drawn with the old tiles, the HUD panel and
        ld (mode), a            ; the old sprites flashed for ~8 frames)
        pop hl
        pop af
        call upload_start
        ld a, ARC_HI_BANK
        jp select_bank
.image: pop hl
        pop hl
        call image_show
        ld a, ARC_HI_BANK
        jp select_bank

; -----------------------------------------------------------------------------
; Tile set change. All three thirds of the screen share one pattern and one
; colour table (VDP_R3/VDP_R4 mask the third bits), so a set is 2 x 1792 bytes.
; upload_start only records the set and asks for a full redraw, which goes
; into the hidden name table while the old picture stays on screen. When it
; is complete, upload_set blanks the display (backdrop = the new set's main
; colour), writes both tables at full speed, shows the new name table and
; turns the display back on: about one frame of flat colour instead of the
; ~24 black frames a live upload took.
; A = bank, HL = set address.
upload_start:
        ld (up_bank), a
        ld (up_set), hl
        xor a                   ; (an armed live switch is for another set)
        ld (live_state), a
        ld a, 1
        ld (up_pending), a
        ld (redraw_all), a
        ret

upload_set:
        ld a, (up_bank)
        call select_bank
        ld hl, (up_set)
        ld a, (hl)              ; tile count -> 8-byte groups
        ld (up_len), a
        ld de, 2 + SET_MAX*8    ; backdrop: the background colour of code 1
