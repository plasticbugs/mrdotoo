; =============================================================================
; render.asm - playfield renderer (runs inside the vblank NMI)
; =============================================================================
; The arcade keeps its two tile layers in video RAM ($7000-$7FFF here). Every
; arcade store into it goes through vstore (the patched write sites), which
; queues the cell. Each vblank the renderer turns queued cells into Screen 2
; name-table entries:
;
;   code = (bg tile == colourway dirt tile ? TBLA : TBLB)[fg tile]
;
; with the colourway's tables and tile set generated by tools/gen_tiles.py.
;
; Screen mapping (player view, the arcade monitor is rotated):
;   screen column sx = arcade native row - 4          (0-23: the playfield)
;   screen row    sy = (31 - arcade native column) - cam
; cam is the first player-view tile row shown: 3, 4 or 5. The playfield is
; 26 rows (player-view rows 3-28) and the screen shows 24; the camera moves in
; 8px steps to follow Mr. Do.
; =============================================================================

SET_BANK0       equ 4           ; tile sets: 4 per bank, banks 4-11
SETS_PER_BANK   equ 4
SET_MAX         equ 224
SET_BYTES       equ 2 + SET_MAX*16
TBL_BANK        equ 12          ; per colourway: TBLA page, TBLB page; then dirt pairs
DIRT_PAIRS      equ $C000 + 31*512
QUEUE_CELLS     equ 128         ; dirty queue: 128 x 2 bytes, one 256-byte page
DRAIN_MAX       equ 40          ; queued cells drawn per vblank
REDRAW_ROWS     equ 6           ; rows per vblank during a full redraw
PF_ROWS         equ 24
CAM_TOP         equ 3
CAM_MID         equ 4
CAM_BOTTOM      equ 5
PLAYER_X        equ ARC_WORK + $1C8     ; arcade $E1C8: Mr. Do, movement axis
PLAYER_FLAGS    equ ARC_WORK + $1C5     ; arcade $E1C5: bit 7 = active

; -----------------------------------------------------------------------------
; vstore: the arcade's video store. A = value, HL = address (CV addresses).
; Preserves BC, DE, HL; clobbers AF. Stores into:
;   $7000-$7FFF  video RAM: store + queue the cell
;   $6000-$6FFF  work RAM: plain store
;   $F000-$FFFF  the arcade's scroll registers: latch into the I/O cells
;   elsewhere    ROM on the arcade board: dropped
; -----------------------------------------------------------------------------
vstore:
        ld (vtmp), a
        ld a, h
        cp $80
        jr nc, .hi
        cp $70
        jr c, .lo
        ld a, (vtmp)
        ld (hl), a
        jp queue_cell
.lo:    cp $60
        ret c
        ld a, (vtmp)
        ld (hl), a
        ret
.hi:    cp $F0
        ret c
        cp $F8
        ld a, (vtmp)
        jr nc, .sy
        ld (IO_SCROLL_X), a
        ret
.sy:    ld (IO_SCROLL_Y), a
        ret

; HL = video address -> dirty queue (producer side). Clobbers AF.
; The NMI only advances q_tail and the arcade only advances q_head, so the
; ring needs no locking. A full queue asks for a full redraw instead.
queue_cell:
        push de
        push hl
        ld a, h
        and 3
        ld d, a
        ld e, l                 ; DE = cell 0-$3FF
        ld a, (q_head)
        ld l, a
        add a, 2
        ld h, a
        ld a, (q_tail)
        cp h
        jr z, .full
        ld a, h
        ld h, high dirty_q
        ld (hl), e
        inc l
        ld (hl), d
        ld (q_head), a          ; publish after the entry is written
        pop hl
        pop de
        ret
.full:  ld a, 1
        ld (redraw_all), a
        pop hl
        pop de
        ret

; The arcade's store forms, reached by rst. All preserve every register and flag.
vh_hl_a:                        ; rst $20: ld (hl),a
        push af
        call vstore
        pop af
        ret
vh_de_a:                        ; rst $28: ld (de),a
        push af
        ex de, hl
        call vstore
        ex de, hl
        pop af
        ret
vh_hl_c:                        ; rst $38: ld (hl),c
        push af
        ld a, c
        call vstore
        pop af
        ret
vh_hl_b:                        ; rst $00: ld (hl),b
        push af
        ld a, b
        call vstore
        pop af
        ret
vh_hl_n:                        ; rst $30 + inline byte: ld (hl),n
        push af
        push hl
        ld hl, 4
        add hl, sp              ; HL -> the return address (points at n)
        push de
        ld e, (hl)
        inc hl
        ld d, (hl)
        ld a, (de)              ; A = n
        inc de
        ld (hl), d              ; return past n
        dec hl
        ld (hl), e
        pop de
        pop hl
        call vstore
        pop af
        ret

; -----------------------------------------------------------------------------
; render: called from the NMI, VDP access allowed. Leaves bank ARC_HI_BANK
; mapped, as the arcade expects.
; -----------------------------------------------------------------------------
render_init:
        xor a
        ld (q_head), a
        ld (q_tail), a
        ld (redraw_all), a
        ld (up_state), a
        ld a, $FF
        ld (cw), a
        ld (cw_attr), a
        ld (cw_tile), a
        ld a, PF_ROWS
        ld (rd_row), a
        ld a, CAM_MID
        ld (cam), a
        ret

render:
        ld a, (up_state)
        or a
        jp nz, upload_step
        ld a, (cw)
        inc a
        call nz, sprites_update ; first, inside vblank
        call check_colourway
        ld a, (up_state)
        or a
        ret nz
        ld a, (cw)
        inc a
        ret z                   ; no tile set yet
        ld a, TBL_BANK
        call select_bank
        call camera_update
        ld a, (redraw_all)
        or a
        jr z, .noreq
        xor a
        ld (redraw_all), a
        ld (rd_row), a          ; restart the full redraw
        ld a, (q_head)          ; everything queued so far is covered by it
        ld (q_tail), a
.noreq: ld a, (rd_row)
        cp PF_ROWS
        jr nc, .drain
        call redraw_rows
        jr .done
.drain: call drain_queue
.done:  ld a, ARC_HI_BANK
        jp select_bank

; Which colourway is on screen? The arcade fills the playfield background with
; the level's dirt; its bottom-left corner cell ($83) identifies it.
check_colourway:
        ld a, (ARC_VRAM + $083)
        ld b, a
        ld a, (ARC_VRAM + $483)
        ld c, a
        ld a, (cw_attr)
        cp b
        jr nz, .changed
        ld a, (cw_tile)
        cp c
        ret z
.changed:
        ld a, b
        ld (cw_attr), a
        ld a, c
        ld (cw_tile), a
        ld a, TBL_BANK
        call select_bank
        ld hl, DIRT_PAIRS
        ld d, 0
.search:
        ld a, (hl)
        cp b
        jr nz, .next
        inc hl
        ld a, (hl)
        dec hl
        cp c
        jr z, .found
.next:  inc hl
        inc hl
        inc d
        ld a, d
        cp 31
        jr nz, .search
        jr .out                 ; not a playfield colourway: keep the current set
.found: ld a, c
        ld (dirt_tile), a
        ld a, d
        ld (tbl_page), a        ; tables at $C000 + cw*512: page = $C0 + cw*2
        add a, a
        add a, $C0
        ld (tbl_page), a
        ld a, (cw)
        cp d
        jr z, .out              ; same tile set (colourways can share a pair)
        ld a, d
        ld (cw), a
        call upload_start
.out:   ld a, ARC_HI_BANK
        jp select_bank

; -----------------------------------------------------------------------------
; Tile set upload: patterns and colours into all three thirds, 512 bytes per
; vblank with the display blanked, then a full redraw.
upload_start:
        ld a, (cw)
        ld b, a
        srl a
        srl a
        add a, SET_BANK0
        ld (up_bank), a
        ld a, b
        and SETS_PER_BANK-1
        ld hl, $C000
        ld de, SET_BYTES
        or a
        jr z, .base
.mul:   add hl, de
        dec a
        jr nz, .mul
.base:  ld (up_set), hl
        ld a, (up_bank)
        call select_bank
        ld a, (hl)              ; tile count
        ld l, a
        ld h, 0
        add hl, hl
        add hl, hl
        add hl, hl
        ld (up_len), hl         ; bytes per table = count * 8
        ld hl, 0
        ld (up_off), hl
        ld a, 1
        ld (up_state), a
        ld hl, VR_SAT           ; no sprites while the tiles change
        call vdp_set_write
        ld a, SAT_END
        out (VDP_DATA), a
        ld a, VDP_R1_ON & ~$40  ; blank the display while tiles change
        ld c, 1
        jp vdp_reg

upload_step:
        ld a, (up_bank)
        call select_bank
        ld a, (up_state)        ; 1-3 patterns (thirds 0-2), 4-6 colours
        dec a
        ld b, a
        ld hl, VR_PT
        ld de, 2                ; set header
        cp 3
        jr c, .pat
        sub 3
        ld hl, VR_CT
        ld de, 2 + SET_MAX*8
.pat:   add a, a                ; + third * $800
        add a, a
        add a, a
        add a, h
        ld h, a
        push de
        ld de, (up_off)
        add hl, de
        call vdp_set_write
        pop de
        ld hl, (up_set)
        add hl, de
        ld de, (up_off)
        add hl, de              ; HL = source
        push hl
        ld hl, (up_len)         ; remaining = len - off, capped at 512
        or a
        sbc hl, de
        ld de, 512
        or a
        sbc hl, de
        jr c, .last
        ld bc, 512
        jr .copy
.last:  add hl, de
        ld b, h
        ld c, l
.copy:  pop hl
        push bc
.loop:  ld a, (hl)
        out (VDP_DATA), a
        inc hl
        dec bc
        ld a, b
        or c
        jr nz, .loop
        pop bc
        ld hl, (up_off)
        add hl, bc
        ld (up_off), hl
        ld de, (up_len)
        or a
        sbc hl, de
        jr c, .done
        ld hl, 0
        ld (up_off), hl
        ld a, (up_state)
        inc a
        ld (up_state), a
        cp 7
        jr c, .done
        xor a                   ; all six tables written
        ld (up_state), a
        inc a
        ld (redraw_all), a
        ld a, VDP_R1_ON
        ld c, 1
        call vdp_reg
.done:  ld a, ARC_HI_BANK
        jp select_bank

; -----------------------------------------------------------------------------
; Camera: follow Mr. Do's cell row (arcade X / 16; row 0 = bottom, 12 = top),
; with hysteresis so it only moves at the playfield edges.
camera_update:
        ld a, (PLAYER_FLAGS)
        rla
        ret nc                  ; Mr. Do not active: keep the camera
        ld a, (PLAYER_X)
        sub $18
        jr nc, .row
        xor a
.row:   rrca
        rrca
        rrca
        rrca
        and $0F                 ; A = cell row
        ld b, a
        ld a, (cam)
        ld c, a
        ld a, b
        or a
        ld a, CAM_BOTTOM
        jr z, .set              ; bottom row: show all of it
        ld a, b
        cp 12
        ld a, CAM_TOP
        jr nc, .set             ; top row
        ld a, c                 ; in between: leave an edge position only
        cp CAM_BOTTOM           ; once Mr. Do is two rows away from it
        jr nz, .nb
        ld a, b
        cp 2
        ret c
        ld a, CAM_MID
        jr .set
.nb:    cp CAM_TOP
        ret nz
        ld a, b
        cp 11
        ret nc
        ld a, CAM_MID
.set:   cp c
        ret z
        ld (cam), a
        ld a, 1
        ld (redraw_all), a      ; picked up at the next check in render
        xor a
        ld (rd_row), a
        ld a, (q_head)
        ld (q_tail), a
        ret

; -----------------------------------------------------------------------------
; Full redraw, REDRAW_ROWS screen rows per call.
redraw_rows:
        ld b, REDRAW_ROWS
.row:   push bc
        ld a, (rd_row)
        cp PF_ROWS
        jr nc, .end
        ld l, a                 ; VRAM = PNT + sy*32
        ld h, 0
        add hl, hl
        add hl, hl
        add hl, hl
        add hl, hl
        add hl, hl
        ld bc, VR_PNT
        add hl, bc
        call vdp_set_write
        ld a, (cam)             ; native column = 31 - (sy + cam)
        ld b, a
        ld a, (rd_row)
        add a, b
        cpl
        and $1F
        ld l, a
        ld h, 0
        ld bc, ARC_VRAM + $400 + 4*32   ; bg tile, native row 4
        add hl, bc
        call draw_run
        ld a, (rd_row)
        inc a
        ld (rd_row), a
        pop bc
        djnz .row
        ret
.end:   pop bc
        ret

; HL = bg-tile address of the first cell; draws 24 cells down the native
; column (= across the screen row) to the current VRAM position.
draw_run:
        ld a, (dirt_tile)
        ld c, a
        ld b, 24
.cell:  ld a, (tbl_page)
        ld d, a
        ld a, (hl)              ; bg tile
        cp c
        jr z, .dirt
        inc d                   ; TBLB
.dirt:  ld a, h
        add a, 8                ; fg tile layer is $800 above the bg tile layer
        ld h, a
        ld e, (hl)
        ld a, (de)
        out (VDP_DATA), a
        ld a, h
        sub 8
        ld h, a
        ld a, l
        add a, 32
        ld l, a
        jr nc, .nc
        inc h
.nc:    djnz .cell
        ret

; -----------------------------------------------------------------------------
; Draw up to DRAIN_MAX queued cells.
drain_queue:
        ld b, DRAIN_MAX
.next:  ld a, (q_tail)
        ld l, a
        ld a, (q_head)
        cp l
        ret z
        ld h, high dirty_q
        ld e, (hl)
        inc l
        ld d, (hl)
        inc l
        ld a, l
        ld (q_tail), a
        push bc
        call draw_cell
        pop bc
        djnz .next
        ret

; DE = cell (native row * 32 + column).
draw_cell:
        ld a, e                 ; native row = cell >> 5
        and $E0
        or d
        rlca
        rlca
        rlca                    ; (D is 0-3: bits land in 0-1 after the rotate)
        sub 4
        cp 24
        ret nc                  ; outside the playfield columns
        ld c, a                 ; C = sx
        ld a, e
        and $1F
        cpl
        and $1F                 ; 31 - column
        ld b, a
        ld a, (cam)
        ld h, a
        ld a, b
        sub h
        cp PF_ROWS
        ret nc                  ; above or below the camera window
        ld l, a                 ; VRAM = PNT + sy*32 + sx
        ld h, 0
        add hl, hl
        add hl, hl
        add hl, hl
        add hl, hl
        add hl, hl
        ld a, l
        or c
        ld l, a
        ld a, h
        add a, high VR_PNT
        ld h, a
        call vdp_set_write
        ld hl, ARC_VRAM + $400
        add hl, de              ; bg tile
        ld a, (dirt_tile)
        ld c, a
        ld a, (tbl_page)
        ld d, a
        ld a, (hl)
        cp c
        jr z, .dirt
        inc d
.dirt:  ld a, h
        add a, 8
        ld h, a
        ld e, (hl)              ; fg tile
        ld a, (de)
        out (VDP_DATA), a
        ret
