; =============================================================================
; render.asm - playfield renderer (runs inside the vblank NMI)
; =============================================================================
; The arcade keeps its two tile layers in video RAM ($7000-$7FFF here). Every
; arcade store into it goes through vstore (the patched write sites), which
; queues the cell. Each vblank the renderer turns queued cells into Screen 2
; name-table entries:
;
;   code = (bg tile == colourway dirt tile ? TBLA : TBLB)[fg tile]
;
; with the colourway's tables and tile set generated by tools/gen_tiles.py.
;
; Screen mapping (player view, the arcade monitor is rotated):
;   screen column sx = arcade native row - 4          (0-23: the playfield)
;   screen row    sy = (31 - arcade native column) - cam
; cam is the first player-view tile row shown: 3, 4 or 5. The playfield is
; 26 rows (player-view rows 3-28) and the screen shows 24; the camera moves in
; 8px steps to follow Mr. Do.
; =============================================================================

SET_BANK0       equ 4           ; tile sets: 4 per bank, banks 4-11
SETS_PER_BANK   equ 4
SET_MAX         equ 224
SET_BYTES       equ 2 + SET_MAX*16
TBL_BANK        equ 12          ; per colourway: TBLA page, TBLB page; then dirt pairs
SCR_BANK0       equ 15          ; non-gameplay screens: sets, hashes, scene data (tools/gen_screens.py)
SCR_INDEX       equ 16          ; bytes per scr_index entry
N_SCREENS       equ (scr_index_end - scr_index) / SCR_INDEX
MODE_NONE       equ 0
MODE_PLAYFIELD  equ 1
MODE_SCREEN     equ 2
DIRT_PAIRS      equ $C000 + 31*512
QUEUE_CELLS     equ 128         ; dirty queue: 128 x 2 bytes, one 256-byte page
DRAIN_MAX       equ 40          ; queued cells drawn per vblank
REDRAW_ROWS     equ 6           ; rows per vblank during a full redraw
REDRAW_ROWS_SCR equ 2           ;   (screen mode: hashed lookups)
PF_ROWS         equ 24
BUSY_MIN        equ 16          ; cell writes per vblank that mean a repaint is still going
RD_WAIT_MAX     equ 30          ; vblanks a full redraw may wait for it
FLIP_WAIT_MAX   equ 8           ; vblanks a finished redraw may wait for the queue
CAM_TOP         equ 3
CAM_MID         equ 4
CAM_BOTTOM      equ 5
PLAYER_X        equ ARC_WORK + $1C8     ; arcade $E1C8: Mr. Do, movement axis
PLAYER_FLAGS    equ ARC_WORK + $1C5     ; arcade $E1C5: bit 7 = active

; -----------------------------------------------------------------------------
; vstore: the arcade's video store. A = value, HL = address (CV addresses).
; Preserves BC, DE, HL; clobbers AF. Stores into:
;   $7000-$7FFF  video RAM: store + queue the cell
;   $6000-$6FFF  work RAM: plain store
;   $F000-$FFFF  the arcade's scroll registers: latch into the I/O cells
;   elsewhere    ROM on the arcade board: dropped
; -----------------------------------------------------------------------------
vstore:
        ld (vtmp), a
        ld a, h
        cp $80
        jr nc, .hi
        cp $70
        jr c, .lo
        ld a, (vtmp)
        ld (hl), a
        jp queue_cell
.lo:    cp $60
        ret c
        ld a, (vtmp)
        ld (hl), a
        ret
.hi:    cp $F0
        ret c
        cp $F8
        ld a, (vtmp)
        jr nc, .sy
        ld (IO_SCROLL_X), a
        ret
.sy:    ld (IO_SCROLL_Y), a
        ret

; HL = video address -> dirty queue (producer side). Clobbers AF.
; The NMI only advances q_tail and the arcade only advances q_head, so the
; ring needs no locking. A full queue asks for a full redraw instead; while
; one is pending, cells are only counted (the redraw covers them), so a bulk
; repaint (the chomper session's 1248-byte fill) costs little and the
; renderer can tell when it has finished.
queue_cell:
        ld a, (redraw_all)
        or a
        jr nz, .count
        push de
        push hl
        ld a, h
        and 3
        ld d, a
        ld e, l                 ; DE = cell 0-$3FF
        ld a, (q_head)
        ld l, a
        add a, 2
        ld h, a
        ld a, (q_tail)
        cp h
        jr z, .full
        ld a, h
        ld h, high dirty_q
        ld (hl), e
        inc l
        ld (hl), d
        ld (q_head), a          ; publish after the entry is written
        pop hl
        pop de
        ret
.full:  ld a, 1
        ld (redraw_all), a
        pop hl
        pop de
        ret
.count: ld a, (q_busy)
        inc a
        ret z                   ; (saturates at 255)
        ld (q_busy), a
        ret

; The arcade's store forms, reached by rst. All preserve every register and flag.
vh_hl_a:                        ; rst $20: ld (hl),a
        push af
        call vstore
        pop af
        ret
vh_de_a:                        ; rst $28: ld (de),a
        push af
        ex de, hl
        call vstore
        ex de, hl
        pop af
        ret
vh_hl_c:                        ; rst $38: ld (hl),c
        push af
        ld a, c
        call vstore
        pop af
        ret
vh_hl_b:                        ; rst $00: ld (hl),b
        push af
        ld a, b
        call vstore
        pop af
        ret
vh_hl_n:                        ; rst $30 + inline byte: ld (hl),n
        push af
        push hl
        ld hl, 4
        add hl, sp              ; HL -> the return address (points at n)
        push de
        ld e, (hl)
        inc hl
        ld d, (hl)
        ld a, (de)              ; A = n
        inc de
        ld (hl), d              ; return past n
        dec hl
        ld (hl), e
        pop de
        pop hl
        call vstore
        pop af
        ret

; -----------------------------------------------------------------------------
; render: called from the NMI, VDP access allowed. Leaves bank ARC_HI_BANK
; mapped, as the arcade expects.
; -----------------------------------------------------------------------------
render_init:
        xor a
        ld (q_head), a
        ld (q_tail), a
        ld (redraw_all), a
        ld (up_pending), a
        ld a, high VR_PNT
        ld (pnt_front), a
        ld a, high VR_PNT2
        ld (pnt_back), a
        ld a, $FF
        ld (cw), a
        ld (scr), a
        xor a
        ld (mode), a
        ld (cw_valid), a
        ld (cw_attr), a
        ld (cw_tile), a
        ld a, PF_ROWS
        ld (rd_row), a
        ld a, CAM_MID
        ld (cam), a
        ret

; Every path out of here must leave ARC_HI_BANK mapped: the arcade's sound data
; and scene code live in that window. render_body may leave any bank mapped.
render:
        call render_body
        ld a, ARC_HI_BANK
        jp select_bank

render_body:
        call scene_vblank       ; a cutscene band's new tiles and names
        ld a, (mode)
        or a
        call nz, sprites_update ; first, inside vblank
        call check_colourway
        ld a, (mode)
        or a
        ret z                   ; no tile set yet
        cp MODE_SCREEN
        ld a, TBL_BANK
        jr nz, .bank
        call scene_update       ; (a cutscene's scrolling band, if any)
        ld a, (scr_hbank)
.bank:  call select_bank
        call camera_update
        ld a, (redraw_all)
        or a
        jr z, .noreq
        ld a, (q_busy)          ; the arcade still writing many cells (a bulk
        cp BUSY_MIN             ; repaint)? Wait for it to finish, keeping
        jr c, .start            ; the old picture on screen
        xor a
        ld (q_busy), a
        ld a, (rd_wait)
        inc a
        ld (rd_wait), a
        cp RD_WAIT_MAX
        jr c, .done
.start: xor a
        ld (q_busy), a
        ld (rd_wait), a
        ld (redraw_all), a
        ld (flip_wait), a
        ld (rd_row), a          ; restart the full redraw
        ld a, (q_head)          ; everything queued so far is covered by it
        ld (q_tail), a
.noreq: ld a, (rd_row)
        cp PF_ROWS
        jr nc, .drain
        call redraw_rows        ; into the hidden name table
        ld a, (rd_row)
        cp PF_ROWS
        jr c, .done
        ld a, (q_head)          ; complete. Cells the arcade changed while
        ld (flip_mark), a       ; it ran (it may have been mid-repaint) go
        ld a, FLIP_WAIT_MAX     ; into it too before it is shown: the queue
        ld (flip_wait), a       ; up to here.
        jr .done
.drain: call drain_queue
        ld a, (flip_wait)
        or a
        jr z, .done
        dec a
        ld (flip_wait), a
        jr z, .show             ; (safety: never wait longer than this)
        ld a, (q_tail)
        ld b, a
        ld a, (flip_mark)
        cp b
        jr nz, .done            ; still catching up
        xor a
        ld (flip_wait), a
.show:  ld a, (up_pending)      ; show it, with its new tile set
        or a
        jr nz, .upload
        call flip_pnt
        jr .done
.upload:
        call upload_set
.done:  ld a, ARC_HI_BANK
        jp select_bank

; Show the name table the last full redraw went into (a scene's band names
; go into it at the next vblank).
flip_pnt:
        ld a, (scn_pbank)
        or a
        jr z, .noband
        ld a, (mode)
        cp MODE_SCREEN
        jr nz, .noband
        ld (scn_ready), a       ; (nonzero)
.noband:
        ld a, (pnt_back)
        ld b, a
        ld a, (pnt_front)
        ld (pnt_back), a
        ld a, b
        ld (pnt_front), a
        rrca                    ; R2 = PNT / $400
        rrca
        and $3F
        ld c, 2
        jp vdp_reg

; Which colourway is on screen? The arcade fills the playfield background with
; the level's dirt; its bottom-left corner cell ($83) identifies it.
check_colourway:
        ld a, (ARC_VRAM + $083)
        ld b, a
        ld a, (ARC_VRAM + $483)
        ld c, a
        ld a, (cw_attr)
        cp b
        jr nz, .changed
        ld a, (cw_tile)
        cp c
        jp z, check_screens
.changed:
        ld a, b
        ld (cw_attr), a
        ld a, c
        ld (cw_tile), a
        ld a, TBL_BANK
        call select_bank
        ld hl, DIRT_PAIRS
        ld d, 0
.search:
        ld a, (hl)
        cp b
        jr nz, .next
        inc hl
        ld a, (hl)
        dec hl
        cp c
        jr z, .found
.next:  inc hl
        inc hl
        inc d
        ld a, d
        cp 31
        jr nz, .search
        xor a                   ; not a playfield colourway
        ld (cw_valid), a
        ld a, ARC_HI_BANK
        call select_bank
        jp check_screens
.found: ld a, 1
        ld (cw_valid), a
        ld a, c
        ld (dirt_tile), a
        ld a, d
        ld (tbl_page), a        ; tables at $C000 + cw*512: page = $C0 + cw*2
        add a, a
        add a, $C0
        ld (tbl_page), a
        ld a, (mode)
        cp MODE_PLAYFIELD
        jr nz, .new
        ld a, (cw)
        cp d
        jr z, .out              ; same tile set (colourways can share a pair)
.new:   ld a, d
        ld (cw), a
        ld a, MODE_PLAYFIELD
        ld (mode), a
        ld a, d                 ; set cw: bank SET_BANK0 + cw/4, slot cw%4
        srl a
        srl a
        add a, SET_BANK0
        ld b, a
        ld a, d
        call set_address
        ld a, b
        call upload_start
.out:   ld a, ARC_HI_BANK
        jp select_bank

; A = slot (0-3) in a set bank -> HL = its address. Preserves B.
set_address:
        and SETS_PER_BANK-1
        ld hl, $C000
        ld de, SET_BYTES
        or a
        ret z
.mul:   add hl, de
        dec a
        jr nz, .mul
        ret

; Not a playfield: is it one of the captured screens (tools/gen_screens.py)?
; Each has a signature: a cell whose fg tile it always shows.
check_screens:
        ld a, (cw_valid)
        or a
        ret nz
        ld hl, scr_index
        ld c, 0
.next:  ld a, c
        cp N_SCREENS
        ret z
        ld e, (hl)
        inc hl
        ld d, (hl)
        inc hl
        push hl
        ld hl, ARC_FG_TILE
        add hl, de
        ld a, (hl)
        pop hl
        cp (hl)
        jr z, .hit
        ld de, SCR_INDEX - 2
        add hl, de
        inc c
        jr .next
.hit:   ld a, (mode)
        cp MODE_SCREEN
        jr nz, .new
        ld a, (scr)
        cp c
        ret z
.new:   ld a, $FF               ; forget the last lookup (new hash table)
        ld (scr_last), a
        ld (scr_last+1), a
        ld a, c
        ld (scr), a
        inc hl                  ; entry +3: camera (fixed per screen)
        ld a, (hl)
        ld (cam), a
        inc hl
        ld a, (hl)              ; set bank
        inc hl
        ld e, (hl)
        inc hl
        ld d, (hl)              ; set address
        inc hl
        push af
        push de
        ld de, scr_hbank        ; hash bank, hash page, band row, band rows,
        ld bc, 6                ; pair hash bank, slot base
        ldir
        xor a
        ld (scn_ready), a       ; a new band starts from scratch
        ld (scn_brow), a
        ld (scn_flush2), a
        ld (scn_lastn), a
        ld (scn_fill), a        ; fill its caches first
        ld a, MODE_SCREEN
        ld (mode), a
        pop hl
        pop af
        call upload_start
        ld a, ARC_HI_BANK
        jp select_bank

; -----------------------------------------------------------------------------
; Tile set change. All three thirds of the screen share one pattern and one
; colour table (VDP_R3/VDP_R4 mask the third bits), so a set is 2 x 1792 bytes.
; upload_start only records the set and asks for a full redraw, which goes
; into the hidden name table while the old picture stays on screen. When it
; is complete, upload_set blanks the display (backdrop = the new set's main
; colour), writes both tables at full speed, shows the new name table and
; turns the display back on: about one frame of flat colour instead of the
; ~24 black frames a live upload took.
; A = bank, HL = set address.
upload_start:
        ld (up_bank), a
        ld (up_set), hl
        ld a, 1
        ld (up_pending), a
        ld (redraw_all), a
        ret

upload_set:
        ld a, (up_bank)
        call select_bank
        ld hl, (up_set)
        ld a, (hl)              ; tile count -> 8-byte groups
        ld (up_len), a
        ld de, 2 + SET_MAX*8    ; backdrop: the background colour of code 1
        ld a, (mode)            ; (plain dirt) on the playfield, code 0 on a
        cp MODE_PLAYFIELD       ; screen
        jr nz, .c0
        ld de, 2 + SET_MAX*8 + 8
.c0:    add hl, de
        ld a, (hl)
        and $0F
        ld c, 7
        call vdp_reg
        ld a, VDP_R1_ON & ~$40
        ld c, 1
        call vdp_reg
        ld hl, VR_PT
        ld de, 2
        call .table
        ld hl, VR_CT
        ld de, 2 + SET_MAX*8
        call .table
        xor a
        ld (up_pending), a
        call flip_pnt
        ld a, VDP_R7
        ld c, 7
        call vdp_reg
        ld a, VDP_R1_ON
        ld c, 1
        jp vdp_reg
; HL = VRAM address, DE = offset in the set. Display blanked: no spacing
; needed between writes.
.table: call vdp_set_write
        ld hl, (up_set)
        add hl, de
        ld c, VDP_DATA
        ld a, (up_len)
        ld e, a
.g:     outi
        outi
        outi
        outi
        outi
        outi
        outi
        outi
        dec e
        jr nz, .g
        ret

; -----------------------------------------------------------------------------
; Camera: follow Mr. Do's cell row (arcade X / 16; row 0 = bottom, 12 = top),
; with hysteresis so it only moves at the playfield edges.
camera_update:
        ld a, (mode)
        cp MODE_SCREEN
        ret z                   ; screens have a fixed camera
        ld a, (PLAYER_FLAGS)
        rla
        ret nc                  ; Mr. Do not active: keep the camera
        ld a, (PLAYER_X)
        sub $18
        jr nc, .row
        xor a
.row:   rrca
        rrca
        rrca
        rrca
        and $0F                 ; A = cell row
        ld b, a
        ld a, (cam)
        ld c, a
        ld a, b
        or a
        ld a, CAM_BOTTOM
        jr z, .set              ; bottom row: show all of it
        ld a, b
        cp 12
        ld a, CAM_TOP
        jr nc, .set             ; top row
        ld a, c                 ; in between: leave an edge position only
        cp CAM_BOTTOM           ; once Mr. Do is two rows away from it
        jr nz, .nb
        ld a, b
        cp 2
        ret c
        ld a, CAM_MID
        jr .set
.nb:    cp CAM_TOP
        ret nz
        ld a, b
        cp 11
        ret nc
        ld a, CAM_MID
.set:   cp c
        ret z
        ld (cam), a
        ld a, 1
        ld (redraw_all), a      ; picked up at the next check in render
        xor a
        ld (rd_row), a
        ld a, (q_head)
        ld (q_tail), a
        ret

; -----------------------------------------------------------------------------
; Full redraw, REDRAW_ROWS screen rows per call.
redraw_rows:
        ld b, REDRAW_ROWS
        ld a, (mode)
        cp MODE_SCREEN
        jr nz, .row
        ld b, REDRAW_ROWS_SCR   ; hashed lookups cost more per cell
.row:   push bc
        ld a, (rd_row)
        cp PF_ROWS
        jr nc, .end
        ld l, a                 ; VRAM = PNT + sy*32
        ld h, 0
        add hl, hl
        add hl, hl
        add hl, hl
        add hl, hl
        add hl, hl
        ld a, (pnt_back)
        ld b, a
        ld c, 0
        add hl, bc
        call vdp_set_write
        ld a, (cam)             ; native column = 31 - (sy + cam)
        ld b, a
        ld a, (rd_row)
        add a, b
        cpl
        and $1F
        ld l, a
        ld h, 0
        ld bc, ARC_VRAM + $400 + 4*32   ; bg tile, native row 4
        add hl, bc
        ld a, (mode)
        cp MODE_SCREEN
        jr z, .scr
        call draw_run
        jr .rowdone
.scr:   ld a, (rd_row)
        call in_band
        jr c, .band
        call draw_run_scr
        jr .rowdone
.band:  ld b, 24                ; the band is scene_update's: black here
        xor a
.bl:    out (VDP_DATA), a
        nop
        nop
        nop
        djnz .bl
.rowdone:
        ld a, (rd_row)
        inc a
        ld (rd_row), a
        pop bc
        djnz .row
        ret
.end:   pop bc
        ret

; A = screen row. Carry if it is in the current screen's scrolling band.
; Preserves everything else.
in_band:
        push bc
        ld c, a
        ld a, (scn_pbank)
        or a
        jr z, .no
        ld a, (scn_row0)
        ld b, a
        ld a, c
        sub b
        jr c, .no
        ld b, a
        ld a, (scn_rows)
        dec a
        cp b                    ; (row - row0) <= rows - 1 ?
        ccf
        jr nc, .no              ; (carry now = row - row0 > rows - 1)
        ld a, c
        scf
        pop bc
        ret
.no:    ld a, c
        or a
        pop bc
        ret

; HL = bg-tile address of the first cell; draws 24 cells down the native
; column (= across the screen row) to the current VRAM position.
draw_run:
        ld a, (dirt_tile)
        ld c, a
        ld b, 24
.cell:  ld a, (tbl_page)
        ld d, a
        ld a, (hl)              ; bg tile
        cp c
        jr z, .dirt
        call not_dirt           ; TBLB page, or A = a dessert plate code (C)
        jr c, .out
.dirt:  ld a, h
        add a, 8                ; fg tile layer is $800 above the bg tile layer
        ld h, a
        ld e, (hl)
        ld a, (de)
        ld e, a
        ld a, h
        sub 8
        ld h, a
        ld a, e
.out:   out (VDP_DATA), a
        ld a, l
        add a, 32
        ld l, a
        jr nc, .nc
        inc h
.nc:    djnz .cell
        ret

; Screen mode: the same run, each cell looked up in the screen's hash.
draw_run_scr:
        ld b, 24
.cell:  push bc
        push hl
        call scr_lookup
        out (VDP_DATA), a
        pop hl
        ld a, l
        add a, 32
        ld l, a
        jr nc, .nc
        inc h
.nc:    pop bc
        djnz .cell
        ret

; HL -> bg tile of a cell. Returns A = the screen tile for its (bg attr,
; bg tile, fg attr, fg tile), or 0 (black) if the capture never saw it.
; 1024-entry open-addressed hash (tools/gen_screens.py), under half full.
; The hash bank is mapped. Clobbers BC, DE, HL.
scr_lookup:
        ld a, h
        sub 4
        ld h, a
        ld b, (hl)              ; bg attr
        add a, 4
        ld h, a
        ld c, (hl)              ; bg tile
        add a, 4
        ld h, a
        ld d, (hl)              ; fg attr
        add a, 4
        ld h, a
        ld e, (hl)              ; fg tile
        ld hl, scr_last         ; same cell contents as the last lookup? (runs of
        ld a, (hl)              ; blank or repeated cells are the common case)
        cp b
        jr nz, .hash
        inc l
        ld a, (hl)
        cp c
        jr nz, .hash
        inc l
        ld a, (hl)
        cp d
        jr nz, .hash
        inc l
        ld a, (hl)
        cp e
        jr nz, .hash
        inc l
        ld a, (hl)
        ret
.hash:  ld hl, scr_last         ; remember this key; the code follows below
        ld (hl), b
        inc l
        ld (hl), c
        inc l
        ld (hl), d
        inc l
        ld (hl), e
        ld a, d                 ; h = (fg tile + 4*(fg attr ^ bg tile ^ bg attr)) & 1023
        xor c
        xor b
        ld l, a
        ld h, 0
        add hl, hl
        add hl, hl
        ld a, l
        add a, e
        ld l, a
        jr nc, .hc
        inc h
.hc:    ld a, h
        and 3
        ld h, a
.probe: push hl
        add hl, hl
        add hl, hl
        ld a, (scr_hpage)
        add a, h
        ld h, a                 ; key = page + h*4
        ld a, (hl)
        cp b
        jr nz, .miss
        inc l
        ld a, (hl)
        cp c
        jr nz, .miss
        inc l
        ld a, (hl)
        cp d
        jr nz, .miss
        inc l
        ld a, (hl)
        cp e
        jr nz, .miss
        pop hl                  ; found: code at page + $1000 + h
        ld a, (scr_hpage)
        add a, $10
        add a, h
        ld h, a
        ld a, (hl)
        ld (scr_last + 4), a
        ret
.miss:  pop hl
        push hl
        ld a, (scr_hpage)       ; empty slot ends the probe
        add a, $10
        add a, h
        ld h, a
        ld a, (hl)
        pop hl
        cp $FF
        jr z, .none
        inc hl
        ld a, h
        and 3
        ld h, a
        jr .probe
.none:  xor a
        ld (scr_last + 4), a
        ret

; A non-dirt cell. HL -> its bg tile, A = the bg tile, D = TBLA page.
; A dessert plate (the center prize: bg attribute bit 7 = character bank 1,
; tiles 0-47) has a fixed code in every set (tools/gen_tiles.py): returns
; carry and A = DESSERT_BASE + tile. Otherwise no carry and D = the TBLB
; page. Only the plate's 2x2 cells ($1CF/$1D0/$1EF/$1F0, arcade $3057) are
; checked: other screens (the instructions' tunnel ends) use bank-1 tiles
; 0-47 too. Preserves BC, HL; clobbers E.
DESSERT_BASE    equ 176
PLATE_H         equ high (ARC_VRAM + $400 + $1CF)
        assert PLATE_H == high (ARC_VRAM + $400 + $1F0)
not_dirt:
        ld e, a
        ld a, h
        cp PLATE_H
        jr nz, .tblb
        ld a, l
        and $DF                 ; $1CF/$1EF -> $CF, $1D0/$1F0 -> $D0
        cp $CF
        jr z, .plate
        cp $D0
        jr nz, .tblb
.plate: ld a, h                 ; bg attribute is $400 below the bg tile
        sub 4
        ld h, a
        ld a, (hl)
        add a, a                ; bit 7 -> carry
        inc h                   ; (inc keeps carry)
        inc h
        inc h
        inc h
        jr nc, .tblb
        ld a, e
        cp 48
        jr nc, .tblb
        add a, DESSERT_BASE
        scf
        ret
.tblb:  inc d
        or a                    ; no carry
        ret

; -----------------------------------------------------------------------------
; Draw up to DRAIN_MAX queued cells.
drain_queue:
        ld b, DRAIN_MAX
.next:  ld a, (q_tail)
        ld l, a
        ld a, (flip_wait)       ; a redraw waiting to be shown takes the
        or a                    ; cells up to flip_mark; later ones go to
        ld a, (q_head)          ; the table on screen after the flip
        jr z, .end
        ld a, (flip_mark)
.end:   cp l
        ret z
        ld h, high dirty_q
        ld e, (hl)
        inc l
        ld d, (hl)
        inc l
        ld a, l
        ld (q_tail), a
        push bc
        call draw_cell
        pop bc
        djnz .next
        ret

; DE = cell (native row * 32 + column).
draw_cell:
        ld a, (mode)            ; a cutscene band's cell (any native row: the
        cp MODE_SCREEN          ; scroll brings them all in) is scene_mark's
        jr nz, .noband
        ld a, (scn_pbank)
        or a
        jr z, .noband
        ld a, (cam)
        ld b, a
        ld a, e
        and $1F
        cpl
        and $1F                 ; 31 - column
        sub b
        call in_band
        jp c, scene_mark
.noband:
        ld a, e                 ; native row = cell >> 5
        and $E0
        or d
        rlca
        rlca
        rlca                    ; (D is 0-3: bits land in 0-1 after the rotate)
        sub 4
        cp 24
        ret nc                  ; outside the playfield columns
        ld c, a                 ; C = sx
        ld a, e
        and $1F
        cpl
        and $1F                 ; 31 - column
        ld b, a
        ld a, (cam)
        ld h, a
        ld a, b
        sub h
        cp PF_ROWS
        ret nc                  ; above or below the camera window
        ld l, a                 ; VRAM = PNT + sy*32 + sx
        ld h, 0
        add hl, hl
        add hl, hl
        add hl, hl
        add hl, hl
        add hl, hl
        ld a, l
        or c
        ld l, a
        ld a, (flip_wait)       ; the hidden table while it waits to be shown
        or a
        ld a, (pnt_front)
        jr z, .front
        ld a, (pnt_back)
.front: add a, h
        ld h, a
        call vdp_set_write
        ld hl, ARC_VRAM + $400
        add hl, de              ; bg tile
        ld a, (mode)
        cp MODE_SCREEN
        jr nz, .pf
        call scr_lookup
        out (VDP_DATA), a
        ret
.pf:    ld a, (dirt_tile)
        ld c, a
        ld a, (tbl_page)
        ld d, a
        ld a, (hl)
        cp c
        jr z, .dirt
        call not_dirt
        jr nc, .dirt
        out (VDP_DATA), a
        ret
.dirt:  ld a, h
        add a, 8
        ld h, a
        ld e, (hl)              ; fg tile
        ld a, (de)
        out (VDP_DATA), a
        ret
