        or a
        jr z, .noband
        ld a, (cam)
        ld b, a
        ld a, e
        and $1F
        cpl
        and $1F                 ; 31 - column
        sub b
        call in_band
        ret c                   ; (scene_write took it at write time)
.noband:
        ld a, (mode)            ; the HUD strips (native columns 0-2, 29-31)
        cp MODE_PLAYFIELD       ; go to the panel (hud.asm)
        jr nz, .nohud
        ld a, e
        and $1F
        cp 3
        jp c, hud_cell
        cp 29
        jp nc, hud_cell
.nohud:
        ld a, e                 ; native row = cell >> 5
        and $E0
        or d
        rlca
        rlca
        rlca                    ; (D is 0-3: bits land in 0-1 after the rotate)
        sub 4
        cp 24
        ret nc                  ; outside the playfield columns
        ld c, a                 ; C = sx
        ld a, e
        and $1F
        cpl
        and $1F                 ; 31 - column
        ld b, a
        ld a, (cam)
        ld h, a
        ld a, b
        sub h
        cp PF_ROWS
        ret nc                  ; above or below the camera window
        ld l, a                 ; VRAM = PNT + sy*32 + sx
        ld h, 0
        add hl, hl
        add hl, hl
        add hl, hl
        add hl, hl
        add hl, hl
        call scr_cellx          ; (a centred screen's column)
        or l
        ld l, a
        ld a, (flip_wait)       ; the hidden table while it waits to be shown
        or a
        ld a, (pnt_front)
        jr z, .front
        ld a, (pnt_back)
.front: add a, h
        ld h, a
        ld (live_va), hl        ; (live_out sets it again)
        call vdp_set_write
        ld hl, ARC_VRAM + $400
        add hl, de              ; bg tile
        ld a, (mode)
        cp MODE_SCREEN
        jr nz, .pf
        push bc                 ; (C = sx, for the edge cells)
        push de                 ; the romhack logo's cells (logo.asm):
        ld a, e                 ; D = screen row, E = column
        and $1F
        cpl
        and $1F
        ld d, a
        ld a, (cam)
        ld e, a
        ld a, d
        sub e
        ld d, a
        ld e, c
        call logo_cell
        pop de
        jr c, .lg
        call scr_lookup
        call clown_keep
        jr nz, .lg
        pop bc                  ; (the arcade's sliding clown: keep the text)
        ret
.lg:    pop bc
        push af                 ; a centred screen's edge cell is repeated
        ld a, c                 ; out to the screen's edge (scr_edge: B =
        ld b, 24                ; 24 the first cell, 1 the last)
        or a
        jr z, .eb
        ld b, 1
        cp 23
        jr z, .eb
        inc b
.eb:    pop af
        call scr_edge
        out (VDP_DATA), a
        ret
.pf:    ld a, (apl_cur_n)       ; a tiled apple's cell? (apples.asm)
        or a
        jr z, .pf2
        ld a, e                 ; screen row = 31 - column - cam
        and $1F
        cpl
        and $1F
        ld b, a
        ld a, (cam)
        ld d, a
        ld a, b
        sub d
        ld (apl_sy), a
        ld a, c                 ; screen column
        call apple_at
        jr nc, .pf2
        jp live_out             ; (a tile set switch's pending code first)
.pf2:   ld a, (dirt_tile)
        ld c, a
        ld a, (tbl_page)
        ld d, a
        ld a, (hl)
        cp c
        jr z, .dirt
        call not_dirt
        jr nc, .dirt
        jp live_out
.dirt:  ld a, h
        add a, 8
        ld h, a
        ld e, (hl)              ; fg tile
        ld a, (de)
        jp live_out
