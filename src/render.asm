        ld h, a
        ld e, (hl)
        ld a, (de)
        ld e, a
        ld a, h
        sub 8
        ld h, a
        ld a, e
.out:   out (VDP_DATA), a
        ld a, l
        add a, 32
        ld l, a
        jr nc, .nc
        inc h
.nc:    djnz .cell
        ret

