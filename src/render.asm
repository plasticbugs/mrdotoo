; C = screen column (0-23) -> A = its name table column: in screen mode
; moved scr_xoff to the right, except column 0, whose write starts at the
; screen's left edge (scr_edge repeats it).
scr_cellx:
        ld a, (mode)
        cp MODE_SCREEN
        ld a, c
        ret nz
        or a
        ret z
        ld a, (scr_xoff)
        add a, c
        ret

; A centred screen (index byte 15, tools/gen_screens.py CENTRED): its 24
; columns sit scr_xoff tiles to the right and each row's first and last cell
; is repeated out to the screen's edges. B = cells left in the run (24 = the
; first, 1 = the last), A = the cell's code: an edge cell writes scr_xoff
; extra copies, spaced (the display is on). Preserves A, BC, DE, HL.
scr_edge:
        push bc
        ld c, a
        ld a, b
        cp 24
        jr z, .edge
        dec a
        jr nz, .no
.edge:  ld a, (scr_xoff)
        or a
        jr z, .no
        ld b, a
.f:     ld a, c
        out (VDP_DATA), a
        nop
        nop
        djnz .f
.no:    ld a, c
        pop bc
        ret

; HL -> bg tile of a cell. Returns A = the screen tile for its (bg attr,
; bg tile, fg attr, fg tile), or 0 (black) if the capture never saw it.
; 1024-entry open-addressed hash (tools/gen_screens.py), under half full.
; The hash bank is mapped. Clobbers BC, DE, HL.
scr_lookup:
        ld a, h
        sub 4
        ld h, a
        ld b, (hl)              ; bg attr
        add a, 4
        ld h, a
        ld c, (hl)              ; bg tile
        add a, 4
        ld h, a
        ld d, (hl)              ; fg attr
        add a, 4
        ld h, a
        ld e, (hl)              ; fg tile
        ld hl, scr_last         ; same cell contents as the last lookup? (runs of
        ld a, (hl)              ; blank or repeated cells are the common case)
        cp b
        jr nz, .hash
        inc l
        ld a, (hl)
        cp c
        jr nz, .hash
        inc l
        ld a, (hl)
        cp d
        jr nz, .hash
        inc l
        ld a, (hl)
        cp e
        jr nz, .hash
        inc l
        ld a, (hl)
        ret
.hash:  ld hl, scr_last         ; remember this key; the code follows below
        ld (hl), b
        inc l
        ld (hl), c
        inc l
        ld (hl), d
        inc l
        ld (hl), e
        call scr_find
        jr c, .hit
        push de                 ; never seen in the capture (the scene's
        ld de, $0000 + BLANK_BG ; details can differ from it): the cell's
        call scr_find           ; background alone, then its foreground
        pop de                  ; alone, then black
        jr c, .miss
        push bc
        ld bc, $0000 + BLANK_BG
        call scr_find
        pop bc
        jr c, .miss
        xor a
.miss:  push af                 ; (scr_miss: clown_keep)
        ld a, 1
        jr .m
.hit:   push af
        xor a
.m:     ld (scr_miss), a
        pop af
.done:  ld (scr_last + 4), a
        ret

; After a cell's lookup in draw_cell: Z = leave the cell as it is. On the
; diamond screen the arcade's own clown slides in from the right across the
; text (its tiles, never captured, miss the hash); the romhack clown stands in
; its box instead, so those writes would only knock holes in the text. The
; arcade redraws the text once its clown has passed. Preserves A.
clown_keep:
        push bc
        ld c, a
        ld a, (logo_on)
        cp 2
        jr nz, .no
        ld a, (scr_miss)
        or a
        jr z, .no
        ld a, c
        cp a                    ; Z
        pop bc
        ret
.no:    or 1                    ; NZ
        ld a, c
        pop bc
        ret

; B, C, D, E = bg attr, bg tile, fg attr, fg tile -> carry and A = the code
; if the screen's hash has the cell. Preserves BC, DE.
scr_find:
        ld a, d                 ; h = (fg tile + 4*(fg attr ^ bg tile ^ bg attr)) & 1023
        xor c
        xor b
        ld l, a
        ld h, 0
        add hl, hl
        add hl, hl
        ld a, l
        add a, e
        ld l, a
        jr nc, .hc
        inc h
.hc:    ld a, h
        and 3
        ld h, a
.probe: push hl
        add hl, hl
        add hl, hl
        ld a, (scr_hpage)
        add a, h
        ld h, a                 ; key = page + h*4
        ld a, (hl)
        cp b
        jr nz, .miss
        inc l
        ld a, (hl)
        cp c
        jr nz, .miss
        inc l
        ld a, (hl)
        cp d
        jr nz, .miss
        inc l
        ld a, (hl)
        cp e
        jr nz, .miss
        pop hl                  ; found: code at page + $1000 + h
        ld a, (scr_hpage)
        add a, $10
        add a, h
        ld h, a
        ld a, (hl)
        scf
        ret
.miss:  pop hl
        push hl
        ld a, (scr_hpage)       ; empty slot ends the probe
        add a, $10
        add a, h
        ld h, a
        ld a, (hl)
        pop hl
        cp $FF
        jr z, .none
        inc hl
        ld a, h
        and 3
        ld h, a
        jr .probe
.none:  or a
        ret

; A non-dirt cell. HL -> its bg tile, A = the bg tile, D = TBLA page.
; A dessert plate (the center prize: bg attribute bit 7 = character bank 1,
; tiles 0-47) has a fixed code in every set (tools/gen_tiles.py): returns
; carry and A = DESSERT_BASE + tile; so has the dessert's score (attribute 9,
; tiles $15-$21, arcade $30FD): SCORE_BASE + tile - $15. Otherwise no carry
; and D = the TBLB
; page. Only the plate's 2x2 cells ($1CF/$1D0/$1EF/$1F0, arcade $3057) are
; checked: other screens (the instructions' tunnel ends) use bank-1 tiles
; 0-47 too. Preserves BC, HL; clobbers E.
DESSERT_BASE    equ 176
SCORE_BASE      equ 163         ; dessert score: "00" here, the other half at +1
SCORE_ATTR      equ $09
PLATE_H         equ high (ARC_VRAM + $400 + $1CF)
        assert PLATE_H == high (ARC_VRAM + $400 + $1F0)
not_dirt:
        ld e, a
        ld a, h
        cp PLATE_H
        jr nz, .tblb
        ld a, l
        and $DF                 ; $1CF/$1EF -> $CF, $1D0/$1F0 -> $D0
        cp $CF
        jr z, .plate
        cp $D0
        jr nz, .tblb
.plate: ld a, h                 ; bg attribute is $400 below the bg tile
        sub 4
        ld h, a
        ld a, (hl)
        inc h
        inc h
        inc h
        inc h
        cp SCORE_ATTR
        jr z, .score
        add a, a                ; bit 7 -> carry
        jr nc, .tblb
        ld a, e
        cp 48
        jr nc, .tblb
        rrca                    ; the dessert (tile / 4) goes into codes
        rrca                    ; PLATE_CODE.. (hud.asm plate_load)
        and $0F
        ld (plate_want), a
        ld a, e
        and 3
        add a, DESSERT_BASE
        scf
        ret
.score: ld a, e                 ; the dessert's score: "00" and "10"-"80"
        sub $15
        cp $22 - $15
        jr nc, .tblb
        or a
        ld a, SCORE_BASE        ; "00"
        jr z, .s00
        ld a, e                 ; the other half: loaded into SCORE_BASE + 1
        ld (score_want), a      ; (hud.asm score_load)
        ld a, SCORE_BASE + 1
.s00:   scf
        ret
.tblb:  inc d
        or a                    ; no carry
        ret

